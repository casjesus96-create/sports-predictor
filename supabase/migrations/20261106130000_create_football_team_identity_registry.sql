-- Team identity registry for the owned football archive.
-- Existing canonical keys are preserved; this does not rewrite match history.
create table if not exists public.football_archive_teams (
    competition_code text not null,
    canonical_team_key text not null,
    display_name text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    primary key (competition_code, canonical_team_key)
);
insert into public.football_archive_teams (competition_code, canonical_team_key, display_name)
select competition_code, home_team_key, max(home_team)
from public.football_match_archive
group by competition_code, home_team_key
on conflict (competition_code, canonical_team_key)
do update set display_name = excluded.display_name, updated_at = now();
insert into public.football_archive_teams (competition_code, canonical_team_key, display_name)
select competition_code, away_team_key, max(away_team)
from public.football_match_archive
group by competition_code, away_team_key
on conflict (competition_code, canonical_team_key)
do update set display_name = excluded.display_name, updated_at = now();

create table if not exists public.football_team_aliases (
    id bigint generated by default as identity primary key,
    competition_code text not null,
    alias_key text not null,
    alias_name text not null,
    canonical_team_key text not null,
    created_by text not null default 'manual_user_confirmation',
    created_at timestamptz not null default now(),
    constraint football_team_aliases_target_fk foreign key (competition_code, canonical_team_key)
        references public.football_archive_teams (competition_code, canonical_team_key),
    constraint football_team_aliases_not_self check (alias_key <> canonical_team_key),
    constraint football_team_aliases_unique unique (competition_code, alias_key)
);
create index if not exists football_team_aliases_target_idx
    on public.football_team_aliases (competition_code, canonical_team_key);

create table if not exists public.football_unresolved_team_names (
    id bigint generated by default as identity primary key,
    provider text not null,
    competition_code text not null,
    original_name text not null,
    normalized_key text not null,
    first_seen_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    seen_count integer not null default 1 check (seen_count > 0),
    constraint football_unresolved_team_names_unique unique (provider, competition_code, normalized_key)
);
create index if not exists football_unresolved_team_names_last_seen_idx
    on public.football_unresolved_team_names (last_seen_at desc);

alter table public.football_archive_teams enable row level security;
alter table public.football_team_aliases enable row level security;
alter table public.football_unresolved_team_names enable row level security;
revoke all on public.football_archive_teams from anon, authenticated;
revoke all on public.football_team_aliases from anon, authenticated;
revoke all on public.football_unresolved_team_names from anon, authenticated;
grant all on public.football_archive_teams to service_role;
grant all on public.football_team_aliases to service_role;
grant all on public.football_unresolved_team_names to service_role;
grant usage, select on all sequences in schema public to service_role;
