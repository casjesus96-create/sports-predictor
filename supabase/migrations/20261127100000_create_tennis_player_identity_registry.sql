-- Exact ATP/WTA player catalog and manually confirmed name aliases.
-- Candidate search is read-only; aliases are only persisted after explicit user confirmation.
create or replace view public.tennis_archive_players
with (security_invoker = true) as
select
    league,
    player_id,
    max(player_name) as player_name,
    max(player_name_key) as player_name_key,
    count(distinct source_match_id)::bigint as matches,
    min(match_date) as first_match,
    max(match_date) as latest_match
from (
    select league, player1_id as player_id, player1_name as player_name,
           player1_name_key as player_name_key, source_match_id, match_date
    from public.tennis_match_archive
    union all
    select league, player2_id as player_id, player2_name as player_name,
           player2_name_key as player_name_key, source_match_id, match_date
    from public.tennis_match_archive
) players
where nullif(trim(player_id), '') is not null
group by league, player_id;

create table if not exists public.tennis_player_aliases (
    id bigint generated by default as identity primary key,
    league text not null check (league in ('ATP', 'WTA')),
    alias_key text not null,
    alias_name text not null,
    player_id text not null,
    canonical_name text not null,
    created_by text not null default 'manual_user_confirmation',
    created_at timestamptz not null default now(),
    constraint tennis_player_aliases_unique unique (league, alias_key),
    constraint tennis_player_aliases_not_blank check (length(trim(alias_key)) > 0),
    constraint tennis_player_aliases_name_not_blank check (length(trim(alias_name)) > 0)
);
create index if not exists tennis_player_aliases_player_idx
    on public.tennis_player_aliases (league, player_id);

alter table public.tennis_player_aliases enable row level security;
revoke all on public.tennis_player_aliases from anon, authenticated;
grant all on public.tennis_player_aliases to service_role;
grant select on public.tennis_archive_players to service_role;
