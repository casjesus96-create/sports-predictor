-- Owned football results archive. Runtime history queries read only this table.
create table if not exists public.football_match_archive (
    id bigint generated by default as identity primary key,
    source_key text not null unique,
    source text not null,
    source_url text not null,
    competition_code text not null,
    competition_name text not null,
    season text not null check (season ~ '^[0-9]{4}$'),
    match_date date not null,
    home_team text not null,
    home_team_key text not null,
    away_team text not null,
    away_team_key text not null,
    home_score integer not null check (home_score >= 0 and home_score <= 30),
    away_score integer not null check (away_score >= 0 and away_score <= 30),
    result text not null check (result in ('H', 'D', 'A')),
    imported_at timestamptz not null default now(),
    constraint football_archive_distinct_teams check (home_team_key <> away_team_key)
);

create index if not exists football_archive_comp_date_idx
    on public.football_match_archive (competition_code, match_date desc);
create index if not exists football_archive_home_team_idx
    on public.football_match_archive (competition_code, home_team_key, match_date desc);
create index if not exists football_archive_away_team_idx
    on public.football_match_archive (competition_code, away_team_key, match_date desc);
create index if not exists football_archive_season_idx
    on public.football_match_archive (competition_code, season);

alter table public.football_match_archive enable row level security;
revoke all on public.football_match_archive from anon, authenticated;
grant all on public.football_match_archive to service_role;
