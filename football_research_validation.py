"""Independent, read-only validation gates for football shadow candidates.

Uses per-match walk-forward predictions already generated by football_backtest.
No fitting, tuning, persistence, provider calls, or model activation occurs here.
"""
from __future__ import annotations

import math
import random
from collections import defaultdict
from typing import Any

OUTCOMES = ("home", "draw", "away")
BOOTSTRAP_REPLICATES = 1000
MIN_HOLDOUT_MATCHES = 100
MIN_HOLDOUT_CLUSTERS = 20
MIN_SEASON_MATCHES = 50
MIN_SEASONS = 3
MIN_SEASON_CONSISTENCY = 0.60


def _losses(row: dict[str, Any], candidate_key: str) -> tuple[float, float, float, float]:
    actual = row["actual_outcome"]
    base = row["base"]
    candidate = row[candidate_key]
    base_brier = sum((base[k] - (1.0 if actual == k else 0.0)) ** 2 for k in OUTCOMES)
    candidate_brier = sum((candidate[k] - (1.0 if actual == k else 0.0)) ** 2 for k in OUTCOMES)
    base_log = -math.log(max(1e-15, base[actual]))
    candidate_log = -math.log(max(1e-15, candidate[actual]))
    return base_brier, candidate_brier, base_log, candidate_log


def _paired_interval(
    differences: list[float], cluster_keys: list[str], seed: int
) -> dict[str, Any]:
    """Cluster bootstrap by kickoff date, preserving same-matchday dependence."""
    n = len(differences)
    if n < 2:
        return {"mean_delta": None, "ci_95": None, "n": n, "cluster_count": len(set(cluster_keys))}
    if len(cluster_keys) != n:
        raise ValueError("Cada diferencia debe tener una clave de jornada/fecha.")

    clusters: dict[str, list[float]] = defaultdict(list)
    for key, difference in zip(cluster_keys, differences):
        clusters[key].append(difference)
    cluster_values = list(clusters.values())
    if len(cluster_values) < 2:
        return {
            "mean_delta": round(sum(differences) / n, 6),
            "ci_95": None,
            "n": n,
            "cluster_count": len(cluster_values),
        }

    mean = sum(differences) / n
    rng = random.Random(seed)
    estimates = []
    for _ in range(BOOTSTRAP_REPLICATES):
        sampled = [cluster_values[rng.randrange(len(cluster_values))] for _ in range(len(cluster_values))]
        sampled_n = sum(len(cluster) for cluster in sampled)
        estimates.append(sum(sum(cluster) for cluster in sampled) / sampled_n)
    estimates.sort()
    lower = estimates[int(0.025 * (BOOTSTRAP_REPLICATES - 1))]
    upper = estimates[int(0.975 * (BOOTSTRAP_REPLICATES - 1))]
    return {
        "mean_delta": round(mean, 6),
        "ci_95": [round(lower, 6), round(upper, 6)],
        "n": n,
        "cluster_count": len(cluster_values),
        "interpretation": "Delta negativo favorece al candidato; el intervalo debe quedar completamente por debajo de cero para evidenciar mejora.",
    }


def _compare(rows: list[dict[str, Any]], candidate_key: str, seed: int) -> dict[str, Any]:
    if not rows:
        empty = _paired_interval([], [], seed)
        return {
            "sample_size": 0, "base_brier": None, "candidate_brier": None,
            "base_log_loss": None, "candidate_log_loss": None,
            "brier_delta": empty, "log_loss_delta": _paired_interval([], [], seed + 1),
        }
    values = [_losses(row, candidate_key) for row in rows]
    n = len(values)
    bb = sum(v[0] for v in values) / n
    cb = sum(v[1] for v in values) / n
    bl = sum(v[2] for v in values) / n
    cl = sum(v[3] for v in values) / n
    cluster_keys = [
        str(row.get("kickoff_at") or "")[:10] or f"row:{index}"
        for index, row in enumerate(rows)
    ]
    return {
        "sample_size": n,
        "base_brier": round(bb, 6), "candidate_brier": round(cb, 6),
        "base_log_loss": round(bl, 6), "candidate_log_loss": round(cl, 6),
        "brier_delta": _paired_interval([v[1] - v[0] for v in values], cluster_keys, seed),
        "log_loss_delta": _paired_interval([v[3] - v[2] for v in values], cluster_keys, seed + 1),
    }


def _season_breakdown(
    rows: list[dict[str, Any]], candidate_key: str, seed: int
) -> list[dict[str, Any]]:
    seasons: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        season = str(row.get("season") or "SIN_TEMPORADA")
        seasons.setdefault(season, []).append(row)
    return [
        {"season": season, **_compare(items, candidate_key, seed + index)}
        for index, (season, items) in enumerate(sorted(seasons.items()))
    ]


def _gate(holdout: dict[str, Any], development_seasons: list[dict[str, Any]]) -> dict[str, Any]:
    n = holdout["sample_size"]
    eligible_seasons = [s for s in development_seasons if s["sample_size"] >= MIN_SEASON_MATCHES]
    consistent = sum(
        1 for s in eligible_seasons
        if s["brier_delta"]["mean_delta"] is not None
        and s["log_loss_delta"]["mean_delta"] is not None
        and s["brier_delta"]["mean_delta"] < 0
        and s["log_loss_delta"]["mean_delta"] < 0
    )
    consistency_rate = consistent / len(eligible_seasons) if eligible_seasons else None
    reasons = []
    if n < MIN_HOLDOUT_MATCHES:
        reasons.append(f"Validación final requiere al menos {MIN_HOLDOUT_MATCHES} partidos; disponibles: {n}.")
    holdout_clusters = holdout["brier_delta"].get("cluster_count", 0)
    if holdout_clusters < MIN_HOLDOUT_CLUSTERS:
        reasons.append(
            f"Holdout requiere al menos {MIN_HOLDOUT_CLUSTERS} jornadas/fechas independientes; "
            f"disponibles: {holdout_clusters}."
        )
    if len(eligible_seasons) < MIN_SEASONS:
        reasons.append(
            f"Desarrollo requiere al menos {MIN_SEASONS} temporadas con {MIN_SEASON_MATCHES}+ partidos; "
            f"disponibles: {len(eligible_seasons)}."
        )
    brier_ci = holdout["brier_delta"].get("ci_95")
    log_ci = holdout["log_loss_delta"].get("ci_95")
    if not brier_ci or brier_ci[1] >= 0:
        reasons.append("El IC 95% emparejado por jornada de Brier no demuestra mejora concluyente.")
    if not log_ci or log_ci[1] >= 0:
        reasons.append("El IC 95% emparejado por jornada de Log Loss no demuestra mejora concluyente.")
    if consistency_rate is None or consistency_rate < MIN_SEASON_CONSISTENCY:
        reasons.append(
            f"La mejora simultánea Brier/Log Loss no alcanza "
            f"{MIN_SEASON_CONSISTENCY:.0%} de temporadas elegibles en desarrollo."
        )
    insufficient = (
        n < MIN_HOLDOUT_MATCHES
        or holdout_clusters < MIN_HOLDOUT_CLUSTERS
        or len(eligible_seasons) < MIN_SEASONS
    )
    status = "APTO_PARA_REVISION" if not reasons else ("MUESTRA_INSUFICIENTE" if insufficient else "NO_APTO")
    return {
        "status": status,
        "reasons": reasons,
        "holdout_minimum": MIN_HOLDOUT_MATCHES,
        "holdout_cluster_minimum": MIN_HOLDOUT_CLUSTERS,
        "holdout_clusters": holdout_clusters,
        "minimum_seasons": MIN_SEASONS,
        "minimum_matches_per_season": MIN_SEASON_MATCHES,
        "required_season_consistency": MIN_SEASON_CONSISTENCY,
        "eligible_seasons": len(eligible_seasons),
        "seasons_improved_on_both_metrics": consistent,
        "season_consistency_rate": round(consistency_rate, 4) if consistency_rate is not None else None,
        "season_consistency_scope": "development_only",
        "automatic_activation": False,
    }


def _row_identity(row: dict[str, Any]) -> tuple[str, ...]:
    match_id = row.get("match_id")
    if match_id is not None:
        return ("id", str(match_id))
    return (
        "fixture",
        str(row.get("kickoff_at") or ""),
        str(row.get("home_team") or ""),
        str(row.get("away_team") or ""),
    )




def _binary_reliability(
    probabilities: list[float],
    observed: list[float],
    *,
    bins: int = 5,
    cluster_keys: list[str] | None = None,
    seed: int = 0,
) -> dict[str, Any]:
    """Describe calibration and date-cluster uncertainty without fitting predictions."""
    if len(probabilities) != len(observed):
        raise ValueError("Probabilidades y resultados observados deben tener la misma longitud.")
    if not probabilities:
        return {"sample_size": 0, "ece": None, "ece_ci_95": None, "bins": [],
                "uncertainty_cluster_count": 0, "bootstrap_replicates": 0}

    def summarize(indices: list[int]) -> tuple[float, list[float | None]]:
        counts = [0] * bins
        predicted_sums = [0.0] * bins
        observed_sums = [0.0] * bins
        for item_index in indices:
            probability = min(1.0, max(0.0, float(probabilities[item_index])))
            outcome = float(observed[item_index])
            bucket_index = min(bins - 1, int(probability * bins))
            counts[bucket_index] += 1
            predicted_sums[bucket_index] += probability
            observed_sums[bucket_index] += outcome
        ece = 0.0
        rates: list[float | None] = []
        total = len(indices)
        for bucket_index, count in enumerate(counts):
            if not count:
                rates.append(None)
                continue
            predicted = predicted_sums[bucket_index] / count
            rate = observed_sums[bucket_index] / count
            rates.append(rate)
            ece += count / total * abs(predicted - rate)
        return ece, rates

    indices = list(range(len(probabilities)))
    point_ece, _ = summarize(indices)
    buckets = []
    for index in range(bins):
        selected = [
            item for item, probability in enumerate(probabilities)
            if min(bins - 1, int(min(1.0, max(0.0, float(probability))) * bins)) == index
        ]
        count = len(selected)
        predicted = sum(float(probabilities[item]) for item in selected) / count if count else None
        rate = sum(float(observed[item]) for item in selected) / count if count else None
        buckets.append({
            "range": f"[{index / bins:.1f},{(index + 1) / bins:.1f}{']' if index == bins - 1 else ')'}",
            "n": count,
            "mean_predicted_probability": round(predicted, 6) if predicted is not None else None,
            "observed_rate": round(rate, 6) if rate is not None else None,
            "absolute_gap": round(abs(predicted - rate), 6) if count else None,
            "observed_rate_ci_95": None,
        })

    if cluster_keys is not None and len(cluster_keys) != len(probabilities):
        raise ValueError("Cada observación debe tener una clave de fecha/jornada.")
    cluster_count = len(set(cluster_keys)) if cluster_keys is not None else 0
    ece_samples: list[float] = []
    rate_samples: list[list[float]] = [[] for _ in range(bins)]
    if cluster_keys is not None and cluster_count >= 2:
        grouped: dict[str, list[int]] = defaultdict(list)
        for item_index, key in enumerate(cluster_keys):
            grouped[str(key)].append(item_index)
        cluster_values = list(grouped.values())
        rng = random.Random(seed)
        for _ in range(BOOTSTRAP_REPLICATES):
            sampled_indices = [
                item_index
                for _ in range(len(cluster_values))
                for item_index in cluster_values[rng.randrange(len(cluster_values))]
            ]
            ece_value, rates = summarize(sampled_indices)
            ece_samples.append(ece_value)
            for bucket_index, rate in enumerate(rates):
                if rate is not None:
                    rate_samples[bucket_index].append(rate)

    def interval(values: list[float]) -> list[float] | None:
        if len(values) < max(100, BOOTSTRAP_REPLICATES // 2):
            return None
        ordered = sorted(values)
        lower = ordered[int(0.025 * (len(ordered) - 1))]
        upper = ordered[int(0.975 * (len(ordered) - 1))]
        return [round(lower, 6), round(upper, 6)]

    for index, bucket in enumerate(buckets):
        bucket["observed_rate_ci_95"] = interval(rate_samples[index])
    return {
        "sample_size": len(probabilities),
        "ece": round(point_ece, 6),
        "ece_ci_95": interval(ece_samples),
        "bins": buckets,
        "uncertainty_cluster_count": cluster_count,
        "bootstrap_replicates": len(ece_samples),
        "uncertainty_method": "Bootstrap percentil por fecha/jornada completa; intervalo descriptivo, no recalibra probabilidades.",
        "interpretation": "ECE es el error de calibración esperado aproximado, ponderado por el tamaño de cada intervalo; no es una métrica de precisión ni una corrección de probabilidades.",
    }



def _binary_market_summary(rows: list[dict[str, Any]], market_key: str, seed: int) -> dict[str, Any]:
    selected = [row for row in rows if market_key in (row.get("markets") or {})]
    if not selected:
        empty = _paired_interval([], [], seed)
        return {
            "sample_size": 0, "base_brier": None, "candidate_brier": None,
            "base_log_loss": None, "candidate_log_loss": None,
            "brier_delta": empty, "log_loss_delta": _paired_interval([], [], seed + 1),
            "observed_rate": None,
            "reliability": {
                "base": _binary_reliability([], []),
                "candidate": _binary_reliability([], []),
            },
        }
    base_brier = []
    candidate_brier = []
    base_log = []
    candidate_log = []
    observed = []
    cluster_keys = []
    for index, row in enumerate(selected):
        item = row["markets"][market_key]
        actual = bool(item["actual"])
        p_base = min(1.0 - 1e-15, max(1e-15, float(item["base"])))
        p_candidate = min(1.0 - 1e-15, max(1e-15, float(item["candidate"])))
        y = 1.0 if actual else 0.0
        base_brier.append((p_base - y) ** 2)
        candidate_brier.append((p_candidate - y) ** 2)
        base_log.append(-(y * math.log(p_base) + (1.0 - y) * math.log(1.0 - p_base)))
        candidate_log.append(-(y * math.log(p_candidate) + (1.0 - y) * math.log(1.0 - p_candidate)))
        observed.append(y)
        cluster_keys.append(str(row.get("kickoff_at") or "")[:10] or f"row:{index}")
    n = len(selected)
    return {
        "sample_size": n,
        "observed_rate": round(sum(observed) / n, 6),
        "base_brier": round(sum(base_brier) / n, 6),
        "candidate_brier": round(sum(candidate_brier) / n, 6),
        "base_log_loss": round(sum(base_log) / n, 6),
        "candidate_log_loss": round(sum(candidate_log) / n, 6),
        "brier_delta": _paired_interval(
            [candidate_brier[i] - base_brier[i] for i in range(n)], cluster_keys, seed
        ),
        "log_loss_delta": _paired_interval(
            [candidate_log[i] - base_log[i] for i in range(n)], cluster_keys, seed + 1
        ),
        "reliability": {
            "base": _binary_reliability(
                [min(1.0, max(0.0, float(row["markets"][market_key]["base"]))) for row in selected],
                observed, cluster_keys=cluster_keys, seed=seed + 2,
            ),
            "candidate": _binary_reliability(
                [min(1.0, max(0.0, float(row["markets"][market_key]["candidate"]))) for row in selected],
                observed, cluster_keys=cluster_keys, seed=seed + 3,
            ),
        },
    }



def _goal_market_season_breakdown(
    rows: list[dict[str, Any]], market_keys: tuple[str, ...]
) -> list[dict[str, Any]]:
    """Season diagnostics use development rows only; they never inspect holdout."""
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        season = str(row.get("season") or "").strip()
        if season:
            grouped[season].append(row)
    result = []
    for season, season_rows in sorted(grouped.items()):
        markets = {}
        for index, market_key in enumerate(market_keys):
            summary = _binary_market_summary(season_rows, market_key, 15000 + index)
            markets[market_key] = {
                "sample_size": summary["sample_size"],
                "base_brier": summary["base_brier"],
                "candidate_brier": summary["candidate_brier"],
                "brier_delta": summary["brier_delta"],
                "base_log_loss": summary["base_log_loss"],
                "candidate_log_loss": summary["candidate_log_loss"],
                "log_loss_delta": summary["log_loss_delta"],
                "base_ece": summary["reliability"]["base"]["ece"],
                "candidate_ece": summary["reliability"]["candidate"]["ece"],
                "eligible_for_descriptive_comparison": summary["sample_size"] >= MIN_SEASON_MATCHES,
            }
        result.append({
            "season": season,
            "sample_size": len(season_rows),
            "markets": markets,
        })
    return result




MIN_TEMPORAL_WINDOW_MATCHES = 50
MIN_TEMPORAL_WINDOW_DATES = 10


def _goal_market_temporal_breakdown(
    rows: list[dict[str, Any]], market_keys: tuple[str, ...]
) -> dict[str, Any]:
    """Compare contiguous development-only time windows without splitting match dates."""
    ordered = sorted(
        rows,
        key=lambda row: (str(row.get("kickoff_at") or ""), str(row.get("match_id") or "")),
    )
    date_groups: list[tuple[str, list[dict[str, Any]]]] = []
    for index, row in enumerate(ordered):
        date_key = str(row.get("kickoff_at") or "")[:10] or "__unknown_date__"
        if date_groups and date_groups[-1][0] == date_key:
            date_groups[-1][1].append(row)
        else:
            date_groups.append((date_key, [row]))

    window_count = min(
        4,
        len(ordered) // MIN_TEMPORAL_WINDOW_MATCHES,
        len(date_groups) // MIN_TEMPORAL_WINDOW_DATES,
    )
    if window_count < 2:
        return {
            "scope": "development_only",
            "window_count": 0,
            "minimum_matches_per_window": MIN_TEMPORAL_WINDOW_MATCHES,
            "minimum_independent_dates_per_window": MIN_TEMPORAL_WINDOW_DATES,
            "windows": [],
            "reason": "Muestra insuficiente para formar al menos dos ventanas temporales comparables.",
        }

    partitions: list[list[tuple[str, list[dict[str, Any]]]]] = []
    cursor = 0
    remaining_matches = len(ordered)
    for window_index in range(window_count):
        remaining_windows = window_count - window_index
        target = remaining_matches / remaining_windows
        selected_groups: list[tuple[str, list[dict[str, Any]]]] = []
        selected_matches = 0
        while cursor < len(date_groups):
            groups_left = len(date_groups) - cursor
            if selected_groups and selected_matches >= target:
                break
            if selected_groups and groups_left <= (remaining_windows - 1) * MIN_TEMPORAL_WINDOW_DATES:
                break
            group = date_groups[cursor]
            selected_groups.append(group)
            selected_matches += len(group[1])
            cursor += 1
        partitions.append(selected_groups)
        remaining_matches -= selected_matches

    windows = []
    for index, groups in enumerate(partitions, start=1):
        window_rows = [row for _, group_rows in groups for row in group_rows]
        dates = [date for date, _ in groups]
        markets = {}
        for market_index, market_key in enumerate(market_keys):
            selected = [
                row for row in window_rows
                if market_key in (row.get("markets") or {})
            ]
            summary = _binary_market_summary(
                window_rows, market_key, 16000 + index * 100 + market_index
            )
            n = len(selected)
            observed_rate = (
                sum(1.0 if bool(row["markets"][market_key]["actual"]) else 0.0 for row in selected) / n
                if n else None
            )
            base_mean = (
                sum(float(row["markets"][market_key]["base"]) for row in selected) / n
                if n else None
            )
            candidate_mean = (
                sum(float(row["markets"][market_key]["candidate"]) for row in selected) / n
                if n else None
            )
            markets[market_key] = {
                "sample_size": n,
                "observed_rate": round(observed_rate, 6) if observed_rate is not None else None,
                "base_mean_probability": round(base_mean, 6) if base_mean is not None else None,
                "candidate_mean_probability": round(candidate_mean, 6) if candidate_mean is not None else None,
                "base_calibration_gap": round(abs(base_mean - observed_rate), 6) if n else None,
                "candidate_calibration_gap": round(abs(candidate_mean - observed_rate), 6) if n else None,
                "base_brier": summary["base_brier"],
                "candidate_brier": summary["candidate_brier"],
                "brier_delta": summary["brier_delta"],
                "base_log_loss": summary["base_log_loss"],
                "candidate_log_loss": summary["candidate_log_loss"],
                "log_loss_delta": summary["log_loss_delta"],
                "base_ece": summary["reliability"]["base"]["ece"],
                "candidate_ece": summary["reliability"]["candidate"]["ece"],
                "eligible_for_descriptive_comparison": (
                    n >= MIN_TEMPORAL_WINDOW_MATCHES
                    and len(dates) >= MIN_TEMPORAL_WINDOW_DATES
                ),
            }
        windows.append({
            "window": index,
            "date_start": dates[0] if dates else None,
            "date_end": dates[-1] if dates else None,
            "sample_size": len(window_rows),
            "independent_dates": len(dates),
            "markets": markets,
        })

    return {
        "scope": "development_only",
        "window_count": len(windows),
        "minimum_matches_per_window": MIN_TEMPORAL_WINDOW_MATCHES,
        "minimum_independent_dates_per_window": MIN_TEMPORAL_WINDOW_DATES,
        "windows": windows,
        "interpretation": "Ventanas cronológicas contiguas; cada fecha calendario permanece completa. Las diferencias describen cambios temporales y no prueban causalidad ni rentabilidad.",
    }



def _expected_goals_summary(rows: list[dict[str, Any]]) -> dict[str, Any]:
    fields = (
        ("home", "actual_home_goals"),
        ("away", "actual_away_goals"),
        ("total", "actual_total_goals"),
    )
    result: dict[str, Any] = {"sample_size": len(rows)}
    for label, actual_key in fields:
        base_errors = []
        candidate_errors = []
        for row in rows:
            actual = float(row[actual_key])
            base_rate = float(row["base_expected_goals"][label])
            candidate_rate = float(row["candidate_expected_goals"][label])
            base_errors.append(abs(base_rate - actual))
            candidate_errors.append(abs(candidate_rate - actual))
        n = len(rows)
        result[label] = {
            "base_mae": round(sum(base_errors) / n, 6) if n else None,
            "candidate_mae": round(sum(candidate_errors) / n, 6) if n else None,
            "delta_mae": round((sum(candidate_errors) - sum(base_errors)) / n, 6) if n else None,
        }
    return result



def _multiclass_window_summary(
    rows: list[dict[str, Any]], candidate_key: str, seed: int
) -> dict[str, Any]:
    """Describe 1X2 performance and one-vs-rest reliability for a time window."""
    comparison = _compare(rows, candidate_key, seed)
    if not rows:
        return {
            **comparison,
            "base_accuracy": None,
            "candidate_accuracy": None,
            "accuracy_delta": None,
            "outcomes": {},
        }

    base_correct = 0
    candidate_correct = 0
    outcomes = {}
    for row in rows:
        actual = row["actual_outcome"]
        base = row["base"]
        candidate = row[candidate_key]
        base_correct += max(OUTCOMES, key=lambda key: base[key]) == actual
        candidate_correct += max(OUTCOMES, key=lambda key: candidate[key]) == actual

    cluster_keys = [
        str(row.get("kickoff_at") or "")[:10] or f"row:{index}"
        for index, row in enumerate(rows)
    ]
    for index, outcome in enumerate(OUTCOMES):
        observed = [1.0 if row["actual_outcome"] == outcome else 0.0 for row in rows]
        outcomes[outcome] = {
            "base": _binary_reliability(
                [float(row["base"][outcome]) for row in rows],
                observed, cluster_keys=cluster_keys, seed=seed + index * 2,
            ),
            "candidate": _binary_reliability(
                [float(row[candidate_key][outcome]) for row in rows],
                observed, cluster_keys=cluster_keys, seed=seed + index * 2 + 1,
            ),
        }

    n = len(rows)
    return {
        **comparison,
        "base_accuracy": round(base_correct / n, 6),
        "candidate_accuracy": round(candidate_correct / n, 6),
        "accuracy_delta": round((candidate_correct - base_correct) / n, 6),
        "outcomes": outcomes,
    }


def _multiclass_temporal_breakdown(
    rows: list[dict[str, Any]], candidate_key: str, seed: int
) -> dict[str, Any]:
    """Compare 1X2 calibration and losses in contiguous development-only windows."""
    ordered = sorted(
        rows,
        key=lambda row: (str(row.get("kickoff_at") or ""), str(row.get("match_id") or "")),
    )
    date_groups: list[tuple[str, list[dict[str, Any]]]] = []
    for index, row in enumerate(ordered):
        date_key = str(row.get("kickoff_at") or "")[:10] or f"__unknown_{index}__"
        if date_groups and date_groups[-1][0] == date_key:
            date_groups[-1][1].append(row)
        else:
            date_groups.append((date_key, [row]))

    window_count = min(
        4,
        len(ordered) // MIN_TEMPORAL_WINDOW_MATCHES,
        len(date_groups) // MIN_TEMPORAL_WINDOW_DATES,
    )
    if window_count < 2:
        return {
            "scope": "development_only",
            "candidate": candidate_key,
            "window_count": 0,
            "minimum_matches_per_window": MIN_TEMPORAL_WINDOW_MATCHES,
            "minimum_independent_dates_per_window": MIN_TEMPORAL_WINDOW_DATES,
            "windows": [],
            "reason": "Muestra insuficiente para formar al menos dos ventanas 1X2 comparables.",
        }

    partitions: list[list[tuple[str, list[dict[str, Any]]]]] = []
    cursor = 0
    remaining_matches = len(ordered)
    for window_index in range(window_count):
        remaining_windows = window_count - window_index
        target = remaining_matches / remaining_windows
        selected_groups: list[tuple[str, list[dict[str, Any]]]] = []
        selected_matches = 0
        while cursor < len(date_groups):
            groups_left = len(date_groups) - cursor
            if selected_groups and selected_matches >= target:
                break
            if selected_groups and groups_left <= (remaining_windows - 1) * MIN_TEMPORAL_WINDOW_DATES:
                break
            group = date_groups[cursor]
            selected_groups.append(group)
            selected_matches += len(group[1])
            cursor += 1
        partitions.append(selected_groups)
        remaining_matches -= selected_matches

    windows = []
    for index, groups in enumerate(partitions, start=1):
        window_rows = [row for _, group_rows in groups for row in group_rows]
        dates = [day for day, _ in groups]
        summary = _multiclass_window_summary(
            window_rows, candidate_key, seed + index * 100
        )
        windows.append({
            "window": index,
            "date_start": dates[0] if dates else None,
            "date_end": dates[-1] if dates else None,
            "sample_size": len(window_rows),
            "independent_dates": len(dates),
            **summary,
            "eligible_for_descriptive_comparison": (
                len(window_rows) >= MIN_TEMPORAL_WINDOW_MATCHES
                and len(dates) >= MIN_TEMPORAL_WINDOW_DATES
            ),
        })

    return {
        "scope": "development_only",
        "candidate": candidate_key,
        "window_count": len(windows),
        "minimum_matches_per_window": MIN_TEMPORAL_WINDOW_MATCHES,
        "minimum_independent_dates_per_window": MIN_TEMPORAL_WINDOW_DATES,
        "windows": windows,
        "interpretation": (
            "Ventanas 1X2 cronológicas del tramo de desarrollo. La calibración "
            "se calcula por clase (local/empate/visitante) uno-contra-el-resto; "
            "no incluye holdout ni modifica probabilidades."
        ),
    }


def _goal_market_validation(
    rows: list[dict[str, Any]], holdout_start: str | None
) -> dict[str, Any]:
    ordered = sorted(
        rows,
        key=lambda row: (str(row.get("kickoff_at") or ""), str(row.get("match_id") or "")),
    )
    cutoff_day = str(holdout_start or "")[:10]
    development = [
        row for row in ordered
        if not cutoff_day or str(row.get("kickoff_at") or "")[:10] < cutoff_day
    ]
    holdout = [
        row for row in ordered
        if cutoff_day and str(row.get("kickoff_at") or "")[:10] >= cutoff_day
    ]
    market_keys = ("btts_yes", "over_1_5", "over_2_5", "over_3_5")
    return {
        "status": "DESCRIPTIVE_RESEARCH_ONLY",
        "development_sample_size": len(development),
        "holdout_sample_size": len(holdout),
        "holdout_start": holdout_start,
        "markets": {
            key: {
                "development": _binary_market_summary(development, key, 11000 + i * 10),
                "holdout": _binary_market_summary(holdout, key, 12000 + i * 10),
            }
            for i, key in enumerate(market_keys)
        },
        "development_season_breakdown": _goal_market_season_breakdown(development, market_keys),
        "temporal_drift": _goal_market_temporal_breakdown(development, market_keys),
        "season_diagnostics_scope": "development_only",
        "minimum_matches_per_season_for_descriptive_comparison": MIN_SEASON_MATCHES,
        "expected_goals_mae": {
            "development": _expected_goals_summary(development),
            "holdout": _expected_goals_summary(holdout),
        },
        "interpretation": {
            "brier_and_log_loss": "En Brier y Log Loss, delta negativo favorece al shadow; las métricas son comparaciones pareadas sobre los mismos partidos.",
            "expected_goals_mae": "En MAE, delta negativo favorece al shadow.",
            "scope": "El holdout se reserva para lectura final; estos resultados son descriptivos y no generan una puerta de activación.",
        },
        "automatic_activation": False,
    }


def build_candidate_validation(evaluation: dict[str, Any]) -> dict[str, Any]:
    """Create independent chronological holdout and development-only consistency gates."""
    rows = sorted(
        evaluation.get("per_match") or [],
        key=lambda row: (str(row.get("kickoff_at") or ""), str(row.get("match_id") or "")),
    )
    advanced_rows = sorted(
        evaluation.get("advanced_goals_shadow_per_match") or [],
        key=lambda row: (str(row.get("kickoff_at") or ""), str(row.get("match_id") or "")),
    )
    goal_market_rows = evaluation.get("goal_market_per_match") or []
    split = max(1, int(len(rows) * 0.8)) if rows else 0
    # Never divide one calendar matchday between development and holdout.
    while 0 < split < len(rows):
        previous_day = str(rows[split - 1].get("kickoff_at") or "")[:10]
        next_day = str(rows[split].get("kickoff_at") or "")[:10]
        if not previous_day or previous_day != next_day:
            break
        split += 1
    development, holdout_rows = rows[:split], rows[split:]

    h2h_development_seasons = _season_breakdown(development, "candidate", 7000)
    h2h_holdout_seasons = _season_breakdown(holdout_rows, "candidate", 8000)
    h2h_holdout = _compare(holdout_rows, "candidate", 8100)
    h2h_gate = _gate(h2h_holdout, h2h_development_seasons)

    advanced_by_id = {_row_identity(row): row for row in advanced_rows}
    advanced_development_rows = [
        {**row, "advanced_shadow": advanced_by_id[_row_identity(row)]["advanced_shadow"]}
        for row in development if _row_identity(row) in advanced_by_id
    ]
    advanced_holdout_rows = [
        {**row, "advanced_shadow": advanced_by_id[_row_identity(row)]["advanced_shadow"]}
        for row in holdout_rows if _row_identity(row) in advanced_by_id
    ]
    advanced_development_seasons = _season_breakdown(
        advanced_development_rows, "advanced_shadow", 9000
    )
    advanced_holdout_seasons = _season_breakdown(
        advanced_holdout_rows, "advanced_shadow", 9500
    )
    advanced_holdout_summary = _compare(advanced_holdout_rows, "advanced_shadow", 10100)
    advanced_gate = _gate(advanced_holdout_summary, advanced_development_seasons)

    return {
        "protocol": "chronological_holdout_cluster_bootstrap_v2",
        "goal_markets": _goal_market_validation(
            goal_market_rows, holdout_rows[0].get("kickoff_at") if holdout_rows else None
        ),
        "temporal_drift_1x2": {
            "scope": "development_only",
            "h2h": _multiclass_temporal_breakdown(
                development, "candidate", 18000
            ),
            "advanced_goals": _multiclass_temporal_breakdown(
                advanced_development_rows, "advanced_shadow", 19000
            ),
        },
        "split": {
            "development_share": 0.8,
            "holdout_share": 0.2,
            "development_matches": len(development),
            "holdout_matches": len(holdout_rows),
            "holdout_start": holdout_rows[0].get("kickoff_at") if holdout_rows else None,
            "holdout_end": holdout_rows[-1].get("kickoff_at") if holdout_rows else None,
            "rule": "El 80% cronológico inicial se usa para consistencia por temporada; el 20% final queda reservado exclusivamente para la puerta de holdout. No se mezclan ambos tramos.",
        },
        # Kept for the existing UI contract; this now deliberately means development only.
        "season_breakdown": h2h_development_seasons,
        "holdout_season_diagnostics": h2h_holdout_seasons,
        "candidates": {
            "h2h": {
                "holdout": h2h_holdout,
                "development_season_breakdown": h2h_development_seasons,
                "holdout_season_diagnostics": h2h_holdout_seasons,
                "gate": h2h_gate,
            },
            "advanced_goals": {
                "holdout": advanced_holdout_summary,
                "development_season_breakdown": advanced_development_seasons,
                "holdout_season_diagnostics": advanced_holdout_seasons,
                "gate": advanced_gate,
            },
        },
        "uncertainty": {
            "method": "Bootstrap emparejado por jornada/fecha, 1000 réplicas deterministas, IC percentil 95%.",
            "cluster_unit": "Fecha calendario de kickoff; todos los partidos del mismo día se remuestrean juntos.",
            "comparison": "Diferencia de pérdida candidato menos Poisson sobre los mismos partidos.",
        },
        "limitations": [
            "La consistencia entre temporadas se calcula solo en el tramo de desarrollo; el holdout final no participa en esa puerta.",
            "El holdout evalúa candidatos ya definidos; cualquier ajuste posterior requiere una nueva muestra temporal no utilizada.",
            "La elegibilidad es una puerta de revisión, no prueba de rentabilidad ni autorización de activación.",
            "Las temporadas son las etiquetas originales del archivo; la cobertura incompleta puede reducir las muestras.",
            "El bootstrap por fecha reduce la falsa independencia entre partidos de una misma jornada, pero no elimina toda dependencia temporal entre jornadas.",
        ],
    }
